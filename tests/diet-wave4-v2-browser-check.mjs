import { chromium } from '/home/ubuntu/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true });
await page.goto('http://127.0.0.1:4173/v2/?wave4=1', { waitUntil: 'networkidle' });
const result = await page.evaluate(() => {
  const api = window.MARSB_V2_STATE;
  api.saveState({});
  const food = { foodId: 'taco-frango-peito-cozido', name: 'Frango peito cozido', source: 'TACO', grams: 150, unit: 'g', nutritionPer100g: { kcal: 163, protein: 31.5, carbs: 0, fats: 3.2 } };
  api.addFoodEntry('2026-10-13', 'almoco', food);
  api.addFoodEntry('2026-10-14', 'almoco', { ...food, grams: 120 });
  api.addWater('2026-10-15', 500);
  const adherence = api.getDietAdherence('2026-10-15');
  const sourceBefore = api.getNutritionDay('2026-10-15');
  api.addFoodEntry('2026-10-15', 'cafe', food);
  const sourceWithFood = api.getNutritionDay('2026-10-15');
  api.addFoodEntry('2026-10-16', 'jantar', { ...food, grams: 50 });
  const duplicate = api.duplicateDietDay('2026-10-15', '2026-10-16', 'add');
  const sourceAfter = api.getNutritionDay('2026-10-15');
  const targetAfter = api.getNutritionDay('2026-10-16');
  const sourceIds = sourceAfter.meals.cafe.map(item => item.id);
  const targetIds = targetAfter.meals.cafe.map(item => item.id);
  const favorite = api.saveDietFavorite('Frango do dia', '2026-10-15');
  const applied = api.applyDietFavorite(favorite.favorite.id, '2026-10-17');
  const appliedDay = api.getNutritionDay('2026-10-17');
  const removed = api.removeDietFavorite(favorite.favorite.id);
  return { adherence, sourceBefore, sourceWithFood, duplicate, sourceAfter, targetAfter, sourceIds, targetIds, favorite, applied, appliedDay, removed, persisted: JSON.parse(localStorage.getItem(api.KEY)) };
});
assert.equal(result.adherence.registeredCount, 3);
assert.equal(result.adherence.rate, 43);
assert.equal(result.duplicate.ok, true);
assert.equal(result.sourceAfter.meals.cafe.length, 1);
assert.equal(result.targetAfter.meals.cafe.length, 1);
assert.notEqual(result.sourceIds[0], result.targetIds[0]);
assert.equal(result.favorite.ok, true);
assert.equal(result.applied.ok, true);
assert.equal(result.appliedDay.meals.cafe.length, 1);
assert.equal(result.removed.ok, true);
assert.equal(result.persisted.nutrition.favorites.length, 0);
await browser.close();
console.log('diet-wave4-v2-browser-check: ok');
