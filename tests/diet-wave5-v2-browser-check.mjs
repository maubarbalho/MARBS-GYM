import { chromium } from '/home/ubuntu/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true });
await page.goto('http://127.0.0.1:4173/v2/?wave5=1', { waitUntil: 'networkidle' });
const result = await page.evaluate(() => {
  const api = window.MARSB_V2_STATE;
  api.saveState({});
  const food = { foodId: 'taco-frango-peito-cozido', name: 'Frango peito cozido', source: 'TACO', grams: 150, unit: 'g', nutritionPer100g: { kcal: 163, protein: 31.5, carbs: 0, fats: 3.2 } };
  api.addFoodEntry('2026-10-16', 'almoco', food);
  api.addFoodEntry('2026-10-16', 'jantar', { ...food, grams: 100 });
  const recipe = api.saveDietRecipe('Bowl de frango', '2026-10-16');
  const prefs = api.saveDietPreferences('sem lactose', 'amendoim');
  const shopping = api.getDietShopping('2026-10-16');
  const applied = api.applyDietRecipe(recipe.recipe.id, '2026-10-17', 'cafe');
  const appliedDay = api.getNutritionDay('2026-10-17');
  const removed = api.removeDietRecipe(recipe.recipe.id);
  const persisted = JSON.parse(localStorage.getItem(api.KEY));
  return { recipe, prefs, shopping, applied, appliedDay, removed, persisted };
});
assert.equal(result.recipe.ok, true);
assert.equal(result.recipe.recipe.ingredients.length, 2);
assert.equal(result.prefs.restrictions, 'sem lactose');
assert.equal(result.prefs.allergies, 'amendoim');
assert.deepEqual(result.shopping, [{ name: 'Frango peito cozido', grams: 250 }]);
assert.equal(result.applied.ok, true);
assert.equal(result.appliedDay.meals.cafe.length, 2);
assert.equal(result.removed.ok, true);
assert.equal(result.persisted.profile.preferences.allergies, 'amendoim');
assert.equal(result.persisted.nutrition.recipes.length, 0);
await browser.close();
console.log('diet-wave5-v2-browser-check: ok');
